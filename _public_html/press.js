(function () {

    var booted = false;

    function bootPressDetail() {

        if (booted) return;

        var container = document.getElementById('eventPage');

        if (!container) return;

        booted = true;

        var params = new URLSearchParams(window.location.search);
        var press  = getPressById(params.get('id'));

        if (!press) {

            container.innerHTML =
                '<div class="ed-notfound">'
                + '<h2>Press not found</h2>'
                + '<p>The coverage you are looking for does not exist or may have been removed.</p>'
                + '<a href="press.html" class="btn-primary">Back to Press</a>'
                + '</div>';

            return;
        }

        renderPressDetail(press);
        initLightbox(getPressImages(press));
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', bootPressDetail, { once: true });
    } else {
        bootPressDetail();
    }

})();
