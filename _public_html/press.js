// Collects the image URLs (PDFs excluded) of one press item, in the
// same order as the data-index values written by renderPressDetail().
function getPressImages(press) {

    var list = [];

    (press.galleries || []).forEach(function (g) {

        (g.images || []).forEach(function (img) {

            if (!img.toLowerCase().endsWith('.pdf')) {
                list.push(img);
            }

        });

    });

    return list;
}


function initLightbox(images) {

    if (!images || !images.length) return;

    var lightbox = document.getElementById('lightbox');
    var img      = document.getElementById('lightboxImg');
    var closeBtn = document.getElementById('lightboxClose');
    var prevBtn  = document.getElementById('lightboxPrev');
    var nextBtn  = document.getElementById('lightboxNext');

    if (!lightbox || !img) return;

    var current = 0;

    function show() {
        img.src = images[current];
    }

    function open(index) {
        current = index;
        show();
        lightbox.classList.add('active');
        document.body.classList.add('lightbox-open');
    }

    function close() {
        lightbox.classList.remove('active');
        document.body.classList.remove('lightbox-open');
    }

    function next() {
        current = (current + 1) % images.length;
        show();
    }

    function prev() {
        current = (current - 1 + images.length) % images.length;
        show();
    }

    // Only image tiles carry data-index; PDF tiles are plain links.
    document.querySelectorAll('.ed-gallery-item[data-index]').forEach(function (item) {

        item.addEventListener('click', function () {
            open(Number(this.dataset.index));
        });

    });

    if (closeBtn) closeBtn.addEventListener('click', close);
    if (nextBtn)  nextBtn.addEventListener('click', next);
    if (prevBtn)  prevBtn.addEventListener('click', prev);

    lightbox.addEventListener('click', function (e) {
        if (e.target === lightbox) close();
    });

    document.addEventListener('keydown', function (e) {

        if (!lightbox.classList.contains('active')) return;

        if (e.key === 'Escape')     close();
        if (e.key === 'ArrowRight') next();
        if (e.key === 'ArrowLeft')  prev();

    });
}



