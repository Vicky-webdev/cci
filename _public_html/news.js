/* ============================================================
   GALLERY
============================================================ */

function renderGallery(gallery) {

  if (!gallery || !gallery.length) return '';

  return '<div class="ed-gallery">'

    + gallery.map(function(g, index) {

        /* YOUTUBE */

        if (typeof g === 'object' && g.type === 'youtube') {

          let embed = g.url;

          if (embed.includes('youtu.be/')) {

            const videoId = embed.split('youtu.be/')[1].split('?')[0];

            embed = 'https://www.youtube.com/embed/' + videoId;

          }

          return '<div class="ed-gallery-item video-item">'
            + '<iframe '
            + 'width="100%" '
            + 'height="315" '
            + 'src="' + embed + '" '
            + 'frameborder="0" '
            + 'allowfullscreen>'
            + '</iframe>'
            + '</div>';

        }

        /* IMAGE */

        return '<div class="ed-gallery-item" data-index="' + index + '">'
          + '<img src="' + g + '" alt="gallery"/>'
          + '</div>';

      }).join('')

    + '</div>';

}


/* ============================================================
   IFRAME ATTRIBUTES (YouTube)
   YouTube refuses to play embeds that arrive without a Referer
   ("Error 153 – Video player configuration error"). The site-wide
   Referrer-Policy header can be "same-origin" (set by Cloudflare),
   which strips it — so give every iframe its own policy, plus the
   permissions YouTube's player expects. Must be applied to the HTML
   string BEFORE it is inserted, since an iframe starts loading as
   soon as it hits the DOM.
============================================================ */

function withEmbedAttributes(html) {

  return html.replace(/<iframe\b([^>]*)>/gi, function (tag, attrs) {

    if (!/\breferrerpolicy\s*=/i.test(attrs)) {
      attrs += ' referrerpolicy="strict-origin-when-cross-origin"';
    }

    if (!/\ballow\s*=/i.test(attrs)) {
      attrs += ' allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share"';
    }

    if (!/\bloading\s*=/i.test(attrs)) {
      attrs += ' loading="lazy"';
    }

    return '<iframe' + attrs + '>';

  });

}


/* ============================================================
   RENDER NEWS
============================================================ */
function renderNews(n) {

  document.title = n.title + ' — Crafts Council of India';

  /* Description */
  const descriptionHtml =
    '<div class="ed-description">'
    + n.description.map(function(p){

        if(
          typeof p === 'string' &&
          (
            p.includes('<div') ||
            p.includes('<iframe') ||
            p.includes('<img') ||
            p.includes('<a') ||
            p.includes('<h1') ||
            p.includes('<h2') ||
            p.includes('<h3')
          )
        ){
          return p;
        }

        return '<p>' + p + '</p>';

    }).join('')
    + '</div>';

  /* Gallery */
  const galleryHtml =
    n.gallery && n.gallery.length
      ? renderGallery(n.gallery)
      : '';

  const html =

    '<div class="ed-hero">'

    + '<div class="ed-hero-bg" style="'
    + (
        n.image
        ? 'background-image:url(' + n.image + ');background-size:cover;background-position:center;'
        : 'background:' + n.heroGradient
      )
    + '"></div>'

    + '<div class="ed-hero-overlay"></div>'

    + '<div class="ed-hero-content">'

    + '<div class="ed-breadcrumb">'
    + '<a href="index.html">Home</a>'
    + '<span>›</span>'
    + '<a href="news.html">News</a>'
    + '<span>›</span>'
    + '<span>' + n.title + '</span>'
    + '</div>'

    + '<h1 class="ed-title">' + n.title + '</h1>'

    + '<p class="ed-subtitle">' + n.subtitle + '</p>'

    + '</div>'
    + '</div>'

    + '<div class="ed-body">'
    + '<div class="ed-main">'

    + descriptionHtml
    + galleryHtml

    + '</div>'
    + '</div>';

  document.getElementById('eventPage').innerHTML = withEmbedAttributes(html);

}
/* ============================================================
   LIGHTBOX
============================================================ */

function initLightbox(images) {

  if (!images || !images.length) return;

  const imageItems = images.filter(function(img) {

    return typeof img === 'string';

  });

  if (!imageItems.length) return;

  const lightbox = document.getElementById('lightbox');

  if (!lightbox) return;

  const img = document.getElementById('lightboxImg');

  const closeBtn = document.getElementById('lightboxClose');

  const prevBtn = document.getElementById('lightboxPrev');

  const nextBtn = document.getElementById('lightboxNext');

  const items = document.querySelectorAll('.ed-gallery-item[data-index]');

  let current = 0;

  function open(index) {

    current = index;

    img.src = imageItems[current];

    lightbox.classList.add('active');

    document.body.classList.add('lightbox-open');

  }

  function close() {

    lightbox.classList.remove('active');

    document.body.classList.remove('lightbox-open');

  }

  function next() {

    current = (current + 1) % imageItems.length;

    img.src = imageItems[current];

  }

  function prev() {

    current = (current - 1 + imageItems.length) % imageItems.length;

    img.src = imageItems[current];

  }

  items.forEach(function(item, index) {

    item.addEventListener('click', function() {

      open(index);

    });

  });

  closeBtn.addEventListener('click', close);

  nextBtn.addEventListener('click', next);

  prevBtn.addEventListener('click', prev);

}


