#!/usr/bin/env node
// Generates src/styles/pages/*.css from the legacy site's per-page inline <style> blocks
// (and custom.css, which only some pages loaded). Each selector is prefixed with
// :where(.pg-<page>) — zero specificity, so the cascade behaves exactly as on the legacy
// page, but rules cannot leak onto other pages after client-side navigation.
// Rules on body/html stay global. Output is committed; rerun after legacy CSS changes.
import fs from "node:fs";
import path from "node:path";
import * as cheerio from "cheerio";
import postcss from "postcss";
import { transform } from "lightningcss";

const SRC = path.resolve("_public_html");
const OUT = path.resolve("src/styles/pages");
fs.mkdirSync(OUT, { recursive: true });

// Browsers silently discard invalid CSS: a rule whose selector list contains an invalid selector
// (legacy "..premium-video iframe") and declarations with invalid values (legacy "!importan").
// The build's CSS parser rejects such input instead, so the same items are removed here,
// using lightningcss's browser-style error recovery only as a validator. Rendering is unchanged.
const invalid = (code) =>
  transform({ filename: "check.css", code: Buffer.from(code), errorRecovery: true }).warnings.length > 0;

function scope(css, cls, origin) {
  const root = postcss.parse(css);
  root.walkRules((rule) => {
    if (rule.parent?.type === "atrule" && /keyframes$/i.test(rule.parent.name)) return;
    if (invalid(`${rule.selector}{}`)) {
      console.warn(`  dropped rule with invalid selector in ${origin}: ${rule.selector.replace(/\s+/g, " ")}`);
      rule.remove();
    }
  });
  root.walkDecls((decl) => {
    if (invalid(`a{${decl.prop}:${decl.value}${decl.important ? " !important" : ""}}`)) {
      console.warn(`  dropped invalid declaration in ${origin}: ${decl.prop}: ${decl.value}`);
      decl.remove();
    }
  });
  root.walkRules((rule) => {
    if (rule.parent?.type === "atrule" && /keyframes$/i.test(rule.parent.name)) return;
    rule.selectors = rule.selectors.map((sel) => {
      const s = sel.trim();
      if (/^(html|body|:root)\b/.test(s)) return s;
      return `:where(.${cls}) ${s}`;
    });
  });
  return `/* Generated by scripts/scope-legacy-css.mjs from ${origin} — do not edit; edit the generator or the legacy source. */\n${root.toString().trim()}\n`;
}

for (const file of fs.readdirSync(SRC).filter((f) => f.endsWith(".html"))) {
  const $ = cheerio.load(fs.readFileSync(path.join(SRC, file), "utf8"));
  const css = $("style").toArray().map((s) => $(s).html() ?? "").join("\n");
  const name = file.replace(/\.html$/, "");
  const target = path.join(OUT, `${name}.css`);
  if (!css.trim()) {
    if (fs.existsSync(target)) fs.rmSync(target);
    continue;
  }
  fs.writeFileSync(target, scope(css, `pg-${name}`, `the inline <style> of _public_html/${file}`));
}
fs.writeFileSync(
  path.join(OUT, "custom.css"),
  scope(fs.readFileSync(path.join(SRC, "custom.css"), "utf8"), "pg-custom", "_public_html/custom.css (loaded only by publication pages)"),
);
console.log("Scoped CSS written to", OUT);
