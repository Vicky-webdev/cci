export type Outcome = "created" | "updated" | "matched" | "skipped" | "duplicate" | "unresolved";

export interface Issue {
  type: string;
  key: string;
  severity: "info" | "warning" | "error";
  message: string;
}

export class ImportReport {
  readonly counts = new Map<string, { discovered: number } & Record<Outcome, number>>();
  readonly issues: Issue[] = [];

  private bucket(type: string) {
    if (!this.counts.has(type)) {
      this.counts.set(type, { discovered: 0, created: 0, updated: 0, matched: 0, skipped: 0, duplicate: 0, unresolved: 0 });
    }
    return this.counts.get(type)!;
  }

  discovered(type: string, n = 1) {
    this.bucket(type).discovered += n;
  }

  outcome(type: string, outcome: Outcome, n = 1) {
    this.bucket(type)[outcome] += n;
  }

  issue(type: string, key: string, severity: Issue["severity"], message: string) {
    this.issues.push({ type, key, severity, message });
  }

  toJSON() {
    return { counts: Object.fromEntries(this.counts), issues: this.issues };
  }

  toMarkdown(meta: { startedAt: Date; finishedAt: Date; mode: string; dryRun: boolean }): string {
    const rows = [...this.counts.entries()]
      .map(
        ([t, c]) =>
          `| ${t} | ${c.discovered} | ${c.created} | ${c.updated} | ${c.matched} | ${c.duplicate} | ${c.skipped} | ${c.unresolved} |`,
      )
      .join("\n");
    const bySeverity = (s: Issue["severity"]) => this.issues.filter((i) => i.severity === s);
    const issueTable = (list: Issue[]) =>
      list.length
        ? "| Type | Key | Message |\n|---|---|---|\n" +
          list.map((i) => `| ${i.type} | \`${i.key.replace(/\|/g, "\\|")}\` | ${i.message.replace(/\|/g, "\\|")} |`).join("\n")
        : "_None._";
    return `# Reconciliation Report

Generated by \`npm run import:legacy\` — do not edit by hand; re-run the import to refresh.

* Run started: ${meta.startedAt.toISOString()}
* Run finished: ${meta.finishedAt.toISOString()}
* Mode: **${meta.mode}**${meta.dryRun ? " (dry run — nothing written)" : ""}

Definitions: **discovered** = records found in the legacy source; **created** = inserted this run;
**updated** = existing record overwritten (only with \`--refresh\`); **matched** = already present from
an earlier run and left untouched; **duplicate** = repeated source record merged into another;
**skipped** = intentionally not imported (reason in the issues below); **unresolved** = could not be
imported and needs a human decision.

## Totals

| Type | Discovered | Created | Updated | Matched | Duplicate | Skipped | Unresolved |
|---|---:|---:|---:|---:|---:|---:|---:|
${rows}

## Errors (${bySeverity("error").length})

${issueTable(bySeverity("error"))}

## Warnings (${bySeverity("warning").length})

${issueTable(bySeverity("warning"))}

## Notes (${bySeverity("info").length})

${issueTable(bySeverity("info"))}
`;
  }
}
